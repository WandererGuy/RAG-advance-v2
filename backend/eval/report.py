"""Read every `results/*.json` -> `results/leaderboard.md`. One row per pipeline.

    python -m eval.report [--results-dir ...] [--out ...] [--stdout]

`golden_set_author` is a column, not a footnote (CLAUDE.md 8, ADR-0004). The leaderboard is the
artefact people paste into a message, and a table of scores with no trace of who wrote the
questions is exactly how an agent-authored number becomes "the system scores 4.6 on
faithfulness" in someone else's slide.

The table stays honest in two other ways:

* **Rows with different `dataset_version` are not comparable**, and the report says so out loud
  rather than sorting them into one ranking.
* **A partial run** (`--limit`) is marked, and a run against an unvalidated corpus is marked.
  Both look identical to a full run once they are a single line in a table.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "results"
LEADERBOARD = RESULTS_DIR / "leaderboard.md"

COLUMNS = [
    "pipeline",
    "dataset",
    "golden_set_author",
    "recall@k",
    "MRR",
    "nDCG@k",
    "faithful",
    "relevance",
    "refusal",
    "cite ok",
    "p50 ms",
    "run",
]


def load_results(directory: Path) -> list[dict[str, Any]]:
    """Every results file except the leaderboard itself, newest run last."""
    payloads: list[dict[str, Any]] = []
    for path in sorted(directory.glob("*.json")):
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise SystemExit(f"error: {path.name} is not valid JSON ({exc.msg})") from exc
        payload["_file"] = path.name
        payloads.append(payload)
    return sorted(payloads, key=lambda p: str(p.get("timestamp", "")))


def row_for(payload: dict[str, Any]) -> list[str]:
    metrics = payload.get("metrics", {})
    retrieval = metrics.get("retrieval", {})
    k = payload.get("config", {}).get("top_k")
    citations = metrics.get("citations", {})

    notes = []
    if payload.get("partial_run"):
        notes.append(f"partial({payload['partial_run']['limit']})")
    if not payload.get("corpus_validated", True):
        notes.append("unvalidated")
    if payload.get("git_dirty"):
        notes.append("dirty")
    if payload.get("failed_questions"):
        notes.append(f"{payload['failed_questions']} failed")

    return [
        f"`{payload.get('pipeline_name', payload['_file'])}`",
        str(payload.get("dataset_version", "?")),
        ", ".join(payload.get("golden_set_author", [])) or "**unknown**",
        _fmt(retrieval.get(f"recall@{k}")),
        _fmt(retrieval.get("mrr")),
        _fmt(retrieval.get(f"ndcg@{k}")),
        _fmt(metrics.get("faithfulness", {}).get("mean")),
        _fmt(metrics.get("answer_relevance", {}).get("mean")),
        _fmt(metrics.get("refusal_accuracy")),
        _fmt(citations.get("citation_rate")),
        str(metrics.get("latency_ms", {}).get("p50") or "—"),
        ", ".join(notes) or "full",
    ]


def render(payloads: list[dict[str, Any]]) -> str:
    if not payloads:
        return (
            "# Leaderboard\n\nNo results yet. Run `make eval P=naive-v1` — the baseline is the "
            "first row.\n"
        )

    lines = [
        "# Leaderboard",
        "",
        "Generated by `make report` from every `results/*.json`. Do not edit by hand.",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "|".join("---" for _ in COLUMNS) + "|",
    ]
    lines += ["| " + " | ".join(row_for(p)) + " |" for p in payloads]

    datasets = {p.get("dataset_version") for p in payloads}
    authors = {a for p in payloads for a in p.get("golden_set_author", [])}
    judges = {p.get("judge_model") for p in payloads if p.get("judge_model")}
    self_judged = [p["pipeline_name"] for p in payloads if p.get("judge_is_answer_model")]

    lines += ["", "## Reading this table", ""]
    if len(datasets) > 1:
        lines.append(
            f"- **Rows do not share a dataset** ({', '.join(sorted(map(str, datasets)))}). "
            "Scores across different dataset versions are not comparable — compare within a "
            "version only."
        )
    if authors == {"agent"}:
        lines.append(
            "- **Every question was written by the agent** (ADR-0004). These numbers are fit "
            "for comparing pipelines against each other and for nothing else; retrieval "
            "metrics are inflated most, `refusal` is the least trustworthy of them."
        )
    if self_judged:
        lines.append(
            f"- **The judge is the answering model** for: {', '.join(sorted(set(self_judged)))} "
            "(ADR-0006). `faithful` and `relevance` are self-graded and biased upward; "
            "`refusal` and every retrieval column are deterministic and are not."
        )
    if judges:
        lines.append(f"- Judge model(s): {', '.join(sorted(map(str, judges)))}.")
    lines.append(
        "- `cite ok` is the share of non-refusal answers carrying at least one citation; the "
        "per-run JSON also counts citations pointing at sources that were never retrieved."
    )
    lines.append(
        "- The corpus is 8 documents. Relative comparison between pipelines is valid; the "
        "absolute values are optimistic."
    )
    return "\n".join(lines) + "\n"


def _fmt(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, int | float):
        return f"{value:.3f}"
    return str(value)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="eval.report", description="Build results/leaderboard.md from every results/*.json."
    )
    parser.add_argument("--results-dir", type=Path, default=RESULTS_DIR)
    parser.add_argument("--out", type=Path, default=LEADERBOARD)
    parser.add_argument("--stdout", action="store_true", help="print instead of writing the file")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if not args.results_dir.exists():
        raise SystemExit(f"error: no results directory at {args.results_dir}")

    payloads = [p for p in load_results(args.results_dir) if p["_file"] != args.out.name]
    markdown = render(payloads)

    if args.stdout:
        print(markdown)
        return 0

    args.out.write_text(markdown, encoding="utf-8")
    print(f"wrote {args.out.relative_to(REPO_ROOT)} ({len(payloads)} pipeline(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
